"""Model files (.esm): a zip holding model.json, a manifest, and optionally the computed solutions and the external
files the model refers to (imported CAD).

Format 2 (this module) adds manifest.json: every stored file with its size and SHA-256, whether solutions were
deliberately left out, and the external assets.  Loading validates it, so a damaged archive is told apart from one
saved without solutions; files without a manifest (format 1) still open.  A solution folder is stored whole
(results, frame geometry and remeshed topology of moving meshes, the solved model snapshot), except Elmer's own
mesh/ case directory, which the next solve regenerates.
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import tempfile
import zipfile

from . import builder as _builder  # noqa: F401  (registers all node types before loading)
from .model import Model

FORMAT = 2
# inside a solution folder: Elmer's case mesh (ElmerGrid output, regenerated by every solve) and the scratch case
# of a deforming-geometry run (its per-step solves; the frames it kept are in results/ and frames.npz)
SKIP_DIRS = {"mesh", "run"}


class ProjectError(RuntimeError):
    pass


def new_workdir() -> str:
    return tempfile.mkdtemp(prefix="elmerstudio_")


def discard_workdir(path: str | None) -> None:
    """Remove a working folder made by new_workdir (meshes, case folders, results of the computed studies) when
    its model is closed; a saved .esm keeps its own copy.  Never touches anything else."""
    if not path:
        return
    p = os.path.abspath(path)
    tmp = os.path.abspath(tempfile.gettempdir())
    if os.path.dirname(p) == tmp and os.path.basename(p).startswith("elmerstudio_") and os.path.isdir(p):
        shutil.rmtree(p, ignore_errors=True)


def _sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def solution_files(workdir: str) -> list[str]:
    """Paths (relative to *workdir*, '/'-separated) of everything a computed solution needs: every file of each
    solution folder (one holding meta.json) and its results/, but not Elmer's mesh/ case directory."""
    out = []
    for root, dirs, files in os.walk(workdir):
        rel_root = os.path.relpath(root, workdir)
        parts = [] if rel_root == "." else rel_root.split(os.sep)
        if parts and parts[0].startswith("_"):
            dirs[:] = []
            continue
        dirs[:] = [d for d in dirs if not (d in SKIP_DIRS and os.path.isfile(os.path.join(root, "meta.json")))]
        in_solution = any(os.path.isfile(os.path.join(workdir, *parts[:i], "meta.json")) for i in range(len(parts) + 1))
        if not in_solution:
            continue
        for f in files:
            if f.endswith(".part"):
                continue
            out.append("/".join(parts + [f]))
    return sorted(out)


def _assets(model: Model) -> dict[str, str]:
    """External files the model refers to: {node tag: absolute path} for file properties that exist on disk."""
    from .model import REGISTRY
    out = {}
    for n in model.root.walk():
        nt = REGISTRY.get(n.kind)
        for p in (nt.props if nt else ()):
            if p.kind == "file":
                path = str(n.props.get(p.key, "") or "").strip()
                if path and os.path.isfile(path):
                    out[f"{n.tag}:{p.key}"] = os.path.abspath(path)
    return out


def save(model: Model, path: str, workdir: str | None, include_solutions=True):
    """Write *path* atomically (a .part file renamed over it once complete)."""
    tmp = path + ".part"
    manifest = {"format": FORMAT, "solutions": "included" if include_solutions else "excluded", "files": {},
                "assets": {}}
    try:
        with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as z:
            z.writestr("model.json", model.to_json())
            if include_solutions and workdir and os.path.isdir(workdir):
                for rel in solution_files(workdir):
                    full = os.path.join(workdir, *rel.split("/"))
                    z.write(full, "work/" + rel)
                    manifest["files"]["work/" + rel] = {"size": os.path.getsize(full), "sha256": _sha256(full)}
            for key, src in _assets(model).items():
                name = "assets/" + key.replace(":", "_") + "_" + os.path.basename(src)
                z.write(src, name)
                manifest["assets"][key] = {"entry": name, "original": src, "size": os.path.getsize(src),
                                           "sha256": _sha256(src)}
            z.writestr("manifest.json", json.dumps(manifest, indent=1))
        os.replace(tmp, path)
    except BaseException:
        try:
            os.remove(tmp)
        except OSError:
            pass
        raise


def _safe_target(root: str, rel: str) -> str:
    """The extraction path of archive entry *rel* under *root*; refuses absolute paths and '..' escapes."""
    parts = rel.replace("\\", "/").split("/")
    if rel.startswith(("/", "\\")) or any(p in ("..",) for p in parts) or (parts and ":" in parts[0]):
        raise ProjectError(f"unsafe path in the model file: {rel}")
    target = os.path.abspath(os.path.join(root, *parts))
    if os.path.commonpath([target, os.path.abspath(root)]) != os.path.abspath(root):
        raise ProjectError(f"unsafe path in the model file: {rel}")
    return target


def load(path: str) -> tuple[Model, str]:
    """Open a model file; returns (model, working folder holding its solutions).  model.load_problems lists
    stored files that are missing or damaged (their solutions cannot be shown); raises ProjectError for unsafe
    archives."""
    workdir = new_workdir()
    problems: list[str] = []
    with zipfile.ZipFile(path) as z:
        names = set(z.namelist())
        data = json.loads(z.read("model.json").decode("utf-8"))
        manifest = json.loads(z.read("manifest.json").decode("utf-8")) if "manifest.json" in names else None
        for name in sorted(names):
            if name.startswith("work/") and not name.endswith("/"):
                target = _safe_target(workdir, name[5:])
                os.makedirs(os.path.dirname(target), exist_ok=True)
                with z.open(name) as src, open(target, "wb") as dst:
                    shutil.copyfileobj(src, dst)
        if manifest is not None:
            for name, info in manifest.get("files", {}).items():
                if name not in names:
                    problems.append(f"missing {name}")
                    continue
                target = _safe_target(workdir, name[5:])
                if os.path.getsize(target) != info.get("size") or _sha256(target) != info.get("sha256"):
                    problems.append(f"damaged {name}")
        m = Model.from_dict(data)
        if manifest is not None:
            for key, info in manifest.get("assets", {}).items():
                tag, prop = key.split(":", 1)
                node = m.by_tag(tag)
                if node is None:
                    continue
                if os.path.isfile(str(node.props.get(prop, ""))):
                    continue                              # the original is still there: keep using it
                entry = info.get("entry", "")
                if entry not in names:
                    problems.append(f"missing asset {entry}")
                    continue
                target = _safe_target(os.path.join(workdir, "_assets"), entry.split("/", 1)[1])
                os.makedirs(os.path.dirname(target), exist_ok=True)
                with z.open(entry) as src, open(target, "wb") as dst:
                    shutil.copyfileobj(src, dst)
                node.props[prop] = target                 # relinked to the packaged copy
    m.file_path = path
    m.load_problems = problems
    m.solutions_saved = (manifest or {}).get("solutions", "included")
    return m, workdir
