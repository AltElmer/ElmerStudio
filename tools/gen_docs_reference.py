"""Generate the Reference pages of the documentation from the model schema (the node registry).

    python tools/gen_docs_reference.py [outdir]

Every Settings window in the GUI is built from the same registry, so these pages list exactly the settings,
units, defaults and choices the GUI shows. Run it after adding or changing a node type; CI runs it before
building the site and fails when the committed pages are out of date.
"""
from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import elmerstudio.core.geometry  # noqa: E402,F401  (registers geometry node types)
import elmerstudio.core.meshing  # noqa: E402,F401
import elmerstudio.core.nodes  # noqa: E402,F401
from elmerstudio.core import physics as P  # noqa: E402
from elmerstudio.core import units as U  # noqa: E402
from elmerstudio.core.materials import LIBRARY, MATPROPS  # noqa: E402
from elmerstudio.core.model import REGISTRY  # noqa: E402
from elmerstudio.core.results import CATALOG, COLOR_TABLES, SHORT, UNIT_FAMILIES  # noqa: E402

HEADER = "// Generated by tools/gen_docs_reference.py from the model schema. Do not edit by hand.\n"

KIND = {"expr": "Expression", "choice": "List", "string": "Text", "bool": "Check box", "int": "Integer",
        "dataset": "Dataset", "objects": "Geometry objects", "rexpr": "Result expression", "text": "Text (multi-line)",
        "runit": "Unit", "expr_table": "Table", "table": "Table", "physics_table": "Table", "savefile": "File name",
        "solnum": "Solutions", "rvexpr": "Vector expression", "study_ref": "Study", "table_ref": "Table",
        "plotgroup": "Plot group", "file": "File", "matprops": "Material properties", "color": "Color",
        "vector": "Vector"}
LEVEL = {"domain": "Domains", "boundary": "Boundaries", "edge": "Edges", "point": "Points"}
DIMS = {"3D": "3D", "2D": "2D", "2Daxi": "2D axisymmetric", "1D": "1D"}


def lit(s) -> str:
    """Inline literal that AsciiDoc leaves alone (no attribute or formatting substitution)."""
    s = str(s).replace("|", "\\|")
    return f"`+{s}+`" if s else ""


def cell(s) -> str:
    return str(s).replace("|", "\\|")


def anchor(kind: str) -> str:
    return kind.replace(".", "-").replace("@", "")


def label_of(p) -> str:
    return p.label.rstrip(": ").strip() or (p.section if p.kind in ("table", "physics_table", "expr_table") else p.key)


def default_of(p) -> str:
    d = p.default
    if p.kind == "bool":
        return "On" if d else "Off"
    if p.kind == "choice":
        for v, lab in p.choices:
            if v == d:
                return cell(lab)
        return lit(d) if d not in ("", None) else ""
    if p.kind in ("table", "expr_table", "physics_table", "matprops", "info", "text"):
        return ""
    if isinstance(d, (list, tuple)):
        return lit(", ".join(str(x) for x in d)) if any(str(x) for x in d) else ""
    if d in ("", None):
        return ""
    return lit(d)


def math(eq: str) -> str:
    eq = eq.strip()
    if eq.startswith("$") and eq.endswith("$"):
        eq = eq[1:-1]
    return "latexmath:[" + eq.replace("]", "\\]") + "]"


def settings_table(nt) -> list[str]:
    props = [p for p in nt.props if p.kind != "info"]
    if not props:
        return []
    out = ['[cols="3,1,1,2,3",options="header",stripes=even]', "|===", "|Setting |Symbol |Unit |Default |Choices / type"]
    section = None
    for p in props:
        if p.section != section:
            section = p.section
            out.append(f'5+h|{cell(section)}')
        sym = cell(p.symbol)
        unit = "length unit" if p.unit == "LEN" else (lit(p.unit) if p.unit else "")
        if p.kind == "choice" and p.choices:
            ch = ", ".join(cell(lab) for _v, lab in p.choices)
        else:
            ch = KIND.get(p.kind, p.kind)
            if p.columns:
                ch += " (columns: " + ", ".join(cell(c[1] if isinstance(c, (tuple, list)) else c)
                                                for c in p.columns) + ")"
        tip = f" +\n_{cell(p.tip)}_" if p.tip else ""
        out.append(f"|{cell(label_of(p))}{tip} |{sym} |{unit} |{default_of(p)} |{ch}")
    out.append("|===")
    return out


def node_section(nt, level=2, where="") -> list[str]:
    h = "=" * (level + 1)
    out = [f"[#{anchor(nt.kind)}]", f"{h} {nt.title}", ""]
    if nt.description:
        out += [nt.description.strip(), ""]
    facts = []
    if nt.selection:
        facts.append(f"Selection: {LEVEL.get(nt.selection, nt.selection)}"
                     + (" (all by default)" if nt.selection_all else ""))
    if tuple(nt.dims) != (1, 2, 3):
        facts.append("Space dimensions: " + ", ".join(f"{d}D" for d in nt.dims))
    if where:
        facts.append(where)
    if facts:
        out += [" · ".join(facts), ""]
    if nt.equation:
        out += [math(nt.equation), ""]
    tab = settings_table(nt)
    out += tab + ([""] if tab else ["No settings.", ""])
    return out


def page(title: str, intro: str, body: list[str]) -> str:
    math_attr = [":page-math: true"] if any("latexmath:[" in line for line in body) else []   # loads MathJax
    return "\n".join([HEADER + f"= {title}", ":page-toclevels: 2", ":description: " + intro.split(".")[0]]
                     + math_attr + ["", intro, ""] + body) + "\n"


def kinds(prefixes) -> list:
    return [nt for k, nt in REGISTRY.items() if any(k == p or k.startswith(p + ".") for p in prefixes)]


# ----------------------------------------------------------------------------------------- pages
def physics_pages(out: dict, nav: list):
    nav.append("** Physics interfaces")
    for pid, d in P.PHYSICS.items():
        fname = f"physics-{pid}.adoc"
        nav.append(f"*** xref:{fname}[{d.name} ({pid})]")
        body = ['[cols="1,3"]', "|===",
                f"|Category |{cell(d.category)}" + (f" › {cell(d.subcategory)}" if d.subcategory else ""),
                f"|Name (tag) |{lit(pid)}",
                "|Space dimensions |" + ", ".join(DIMS.get(x, x) for x in d.dims),
                "|Studies |" + ", ".join(P.STUDY_TYPES[s][0] for s in d.studies if s in P.STUDY_TYPES),
                "|Dependent variables |" + ", ".join(f"{lit(sym)} {cell(lab)} ({lit(unit)})"
                                                    for sym, (_v, lab, unit) in d.depvars.items()),
                "|Default features |" + ", ".join(f"<<{anchor(k)},{REGISTRY[k].title}>>"
                                                 for k, _l in d.defaults if k in REGISTRY),
                "|===", ""]
        if d.equation:
            body += [math(d.equation), ""]
        if d.mat_props:
            body += ["Material properties used: " + ", ".join(
                f"{MATPROPS[k][0]} ({MATPROPS[k][1]})" if k in MATPROPS else lit(k) for k in d.mat_props) + ".", ""]
        root = REGISTRY.get(d.kind)
        if root is not None:
            body += ["== Interface settings", ""] + settings_table(root) + [""]
        seen = set()
        for lvl in ("domain", "boundary", "edge", "point"):
            ks = [k for k in getattr(d, lvl) if k in REGISTRY]
            ks += [k for k, l in d.defaults if l == lvl and k in REGISTRY and k not in ks]
            if not ks:
                continue
            where = f"Physics ribbon › {LEVEL[lvl]}, or right-click the interface in the Model Builder"
            body += [f"== {LEVEL[lvl][:-1] if lvl != 'boundary' else 'Boundary'} features", ""]
            for k in ks:
                if k in seen:
                    continue
                seen.add(k)
                body += node_section(REGISTRY[k], 2, where)
        rest = [nt for nt in kinds([pid]) if nt.kind not in seen and nt.kind != d.kind]
        if rest:
            body += ["== Other features", ""]
            for nt in rest:
                body += node_section(nt, 2)
        rv = [r for r in CATALOG if r[0].startswith(pid + ".") or r[0] in d.depvars]
        if rv:
            body += ["== Result variables", "", '[cols="2,4,1",options="header"]', "|===",
                     "|Name |Description |Unit"]
            body += [f"|{lit(a)} |{cell(lab)} |{lit(u)}" for a, _s, _c, lab, u, _k in rv]
            body += ["|===", ""]
        out[fname] = page(f"{d.name} ({pid})", d.description.strip() or d.name + ".", body)


def multiphysics_page(out, nav):
    body = []
    for name, (title, _icon, ids, cpl) in P.BUNDLES.items():
        body.append(f"* *{title}* in the Model Wizard adds " + " and ".join(
            f"xref:physics-{i}.adoc[{P.PHYSICS[i].name}]" for i in ids) + " with the coupling below.")
    body.append("")
    for nt in kinds(["multiphysics", "mp"]):
        body += node_section(nt, 1, "Home ribbon › Multiphysics")
    out["multiphysics.adoc"] = page("Multiphysics couplings", "Couplings between two physics interfaces. "
                                    "They appear under Multiphysics in the Model Builder once both interfaces exist.", body)
    nav.append("*** xref:multiphysics.adoc[Multiphysics couplings]")


def simple_page(out, nav, fname, title, intro, prefixes, where="", navlabel=None):
    body = []
    for nt in kinds(prefixes):
        body += node_section(nt, 1, where)
    out[fname] = page(title, intro, body)
    nav.append(f"** xref:{fname}[{navlabel or title}]")


def materials_page(out, nav):
    body = ["== Material properties", "", '[cols="3,1,2,3,2",options="header"]', "|===",
            "|Property |Symbol |Unit |Elmer keyword |Group"]
    for k, (name, sym, unit, kw, grp) in MATPROPS.items():
        body.append(f"|{cell(name)} |{cell(sym)} |{lit(unit)} |{lit(kw)} |{cell(grp)}")
    body += ["|===", "", "== Material library", "",
             "Properties at 20 °C. Any value can be replaced by an expression, for example a temperature-dependent "
             "conductivity `+k0*(1+0.002*(T-293.15[K]))+`.", ""]
    keys = list(MATPROPS)
    body += [f'[cols="2,2,{",".join("1" for _ in keys)}",options="header",stripes=even]', "|===",
             "|Material |Library " + " ".join(f"|{cell(MATPROPS[k][1])}" for k in keys)]
    for name, (cat, props, *_rest) in LIBRARY.items():
        body.append(f"|{cell(name)} |{cell(cat)} " + " ".join(f"|{lit(props.get(k, ''))}" for k in keys))
    body += ["|===", ""]
    for nt in kinds(["materials", "material"]):
        body += node_section(nt, 1)
    out["materials.adoc"] = page("Materials", "Material properties the physics interfaces read, and the built-in "
                                 "material library (Materials ribbon › Add Material).", body)
    nav.append("** xref:materials.adoc[Materials]")


def variables_page(out, nav):
    body = ['[cols="2,4,1,1",options="header",stripes=even]', "|===", "|Name |Description |Unit |Kind"]
    for a, _s, _c, lab, u, k in CATALOG:
        body.append(f"|{lit(a)} |{cell(lab)} |{lit(u)} |{k}")
    body += ["|===", "", "== Short names", "",
             "These short names are accepted in result expressions as well:", ""]
    body += [f"* {lit(s)} = {lit(full)}" for s, full in SHORT.items()]
    body += ["", "== Unit families", "",
             "A plot or evaluation can show a quantity in any unit of its family "
             "(the *Unit* list next to the expression):", ""]
    body += ["* " + ", ".join(lit(u) for u in fam) for fam in UNIT_FAMILIES]
    body += ["", "== Color tables", "", ", ".join(lit(c) for c in COLOR_TABLES) + ".", ""]
    out["result-variables.adoc"] = page("Result variables", "Variables available in result expressions "
                                        "(plots, datasets, derived values). A variable is listed in the GUI "
                                        "only when the solution contains it.", body)
    nav.append("** xref:result-variables.adoc[Result variables]")


def expressions_page(out, nav):
    body = ["== Operators", "",
            "`+ - * / ^` (power; `**` works too), parentheses, comparisons `< <= > >= == !=` "
            "(true = 1, false = 0), for example `+T0 + 5[K]*(t > 10[s])+`.", "",
            "== Functions", "", ", ".join(lit(f) for f in U.MATH_FUNCS) + ".", "",
            "Two-argument `+min(a, b)+` and `+max(a, b)+` work in every expression; in physics settings they are "
            "exported to Elmer as small MATC helper functions.", "",
            "== Constants", "", '[cols="1,2",options="header"]', "|===", "|Name |Value"]
    body += [f"|{lit(k)} |{lit(repr(v) if not isinstance(v, complex) else 'imaginary unit')}"
             for k, v in U.CONSTANTS.items()]
    body += ["|===", "", "== Units", "",
             "Write a unit in square brackets after a number or parameter: `+10[mm]+`, `+20[degC]+`, "
             "`+5[W/(m^2*K)]+`, `+n[rpm]+`. Values are converted to SI before Elmer sees them.", "",
             "SI prefixes (" + ", ".join(lit(p) for p in U._PREFIX) + ") work with: "
             + ", ".join(lit(u) for u in U._PREFIXABLE) + ".", "",
             "Other units: " + ", ".join(lit(u) for u in U._PLAIN) + ".", "",
             "Temperatures with an offset: " + ", ".join(lit(u) for u in U._AFFINE)
             + ". A temperature *difference* is written in `+K+`.", ""]
    out["expressions.adoc"] = page("Expressions and units", "The expression syntax used in parameters, "
                                   "variables, material properties, physics settings and results.", body)
    nav.append("** xref:expressions.adoc[Expressions and units]")


def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "docs", "modules", "reference")
    out: dict[str, str] = {}
    nav = ["* Reference", "** xref:index.adoc[Overview]"]
    physics_pages(out, nav)
    multiphysics_page(out, nav)
    simple_page(out, nav, "definitions.adoc", "Definitions", "Parameters, functions, variables and component "
                "couplings (Home or Definitions ribbon).", ["global", "params", "func", "definitions", "variables", "cpl"])
    simple_page(out, nav, "geometry.adoc", "Geometry features", "Every geometry feature of the Geometry ribbon. "
                "Lengths are in the geometry's length unit unless a unit is written.", ["geometry", "geom"],
                "Geometry ribbon")
    materials_page(out, nav)
    simple_page(out, nav, "mesh.adoc", "Mesh", "Mesh sequence nodes (Mesh ribbon).", ["mesh"], "Mesh ribbon")
    simple_page(out, nav, "studies.adoc", "Studies and solvers", "Study steps, parametric sweeps and solver "
                "configurations (Study ribbon).", ["study"], "Study ribbon")
    simple_page(out, nav, "datasets.adoc", "Datasets", "Datasets of the Results ribbon. A dataset is what a plot "
                "or evaluation is computed on.", ["dset"], "Results ribbon › Datasets")
    simple_page(out, nav, "derived-values.adoc", "Derived values", "Integrals, averages, extrema and point values; "
                "results go to a Table.", ["eval", "table"], "Results ribbon › Evaluation")
    simple_page(out, nav, "plots.adoc", "Plot groups and plots", "Plot groups and every plot type of the Results "
                "ribbon.", ["pg3d", "pg2d", "pg1d", "pgpolar", "plot"], "Results ribbon")
    simple_page(out, nav, "export.adoc", "Export", "Images, data, VTU files and HTML reports.", ["export"],
                "Results ribbon › Export")
    variables_page(out, nav)
    expressions_page(out, nav)
    os.makedirs(os.path.join(outdir, "pages"), exist_ok=True)
    for f in os.listdir(os.path.join(outdir, "pages")):
        if f not in out and f != "index.adoc" and f.endswith(".adoc"):
            os.remove(os.path.join(outdir, "pages", f))
    for fname, text in out.items():
        with open(os.path.join(outdir, "pages", fname), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    with open(os.path.join(outdir, "nav.adoc"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + "\n".join(nav) + "\n")
    print(f"{len(out)} pages in {outdir}")


if __name__ == "__main__":
    main()
