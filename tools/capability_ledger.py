#!/usr/bin/env python3
"""Generate capability documentation from docs/capabilities.yml.

Outputs:
- docs/modules/ROOT/pages/capabilities.adoc (summary table)
- updates docs/modules/ROOT/pages/comsol-users.adoc (links to capabilities)
- updates docs/modules/ROOT/pages/known-limitations.adoc (auto-generated from capabilities)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
CAP_FILE = ROOT / "docs" / "capabilities.yml"
DOCS_DIR = ROOT / "docs" / "modules" / "ROOT" / "pages"


def load_capabilities() -> dict[str, Any]:
    with open(CAP_FILE) as f:
        return yaml.safe_load(f)


def generate_capabilities_adoc(cap: dict[str, Any]) -> str:
    """Generate the capabilities.adoc page."""
    lines = [
        "= Physics capabilities",
        ":description: Versioned capability ledger for Elmer Studio physics interfaces, formulations, studies, and backends.",
        "",
        "This page is generated from `docs/capabilities.yml` by `tools/capability_ledger.py`.",
        "Do not edit directly; update the YAML source and regenerate.",
        "",
        f"Last updated: {cap.get('summary', {}).get('last_updated', 'unknown')}",
        f"Generated by: {cap.get('summary', {}).get('generated_by', 'unknown')}",
        "",
        "== Summary",
        "",
        f"* Total physics interfaces: {cap.get('summary', {}).get('total_physics', 0)}",
        f"* Qualified backends: {cap.get('summary', {}).get('qualified_backends', 0)}",
        f"* Partly qualified backends: {cap.get('summary', {}).get('partly_qualified_backends', 0)}",
        f"* Not qualified backends: {cap.get('summary', {}).get('not_qualified_backends', 0)}",
        "",
        "=== Supported backends",
        "",
    ]
    for b in cap.get('summary', {}).get('backends', []):
        lines.append(f"* {b}")

    lines += [
        "",
        "== Physics interfaces",
        "",
    ]

    for phys in cap.get('capabilities', []):
        lines += [
            f"=== {phys['name']} (`physics.{phys['id']}`)",
            "",
            f"* Category: {phys['category']}{' / ' + phys.get('subcategory', '') if phys.get('subcategory') else ''}",
            f"* Dimensions: {', '.join(phys['dimensions'])}",
            f"* Studies: {', '.join(phys['studies'])}",
            f"* Material laws: {', '.join(phys['material_laws'])}",
            f"* Mesh: {', '.join(phys['mesh'])}",
            "",
            "==== Formulations",
            "",
        ]
        for form in phys['formulations']:
            lines.append(f"* {form}")
        lines += [
            "",
            "==== Couplings",
            "",
        ]
        for c in phys['couplings']:
            lines.append(f"* {c}")
        lines += [
            "",
            "==== Backends",
            "",
        ]
        for b in phys['backends']:
            status_badge = {
                'qualified': '[Qualified]',
                'partly qualified': '[Partly qualified]',
                'not qualified': '[Not qualified]',
            }.get(b['status'], b['status'])
            lines.append(f"* **{b['name']}** ({b['version']}) — {status_badge}")
            for lim in b.get('limitations', []):
                lines.append(f"  * {lim}")
            for ev in b.get('evidence', []):
                lines.append(f"  * Evidence: `{ev}`")
        lines += [
            "",
            "==== Features",
            "",
            f"* Domain features: {', '.join(phys['features']['domain'])}",
            f"* Boundary features: {', '.join(phys['features']['boundary'])}",
            "",
            "==== Result variables",
            "",
            f"* {', '.join(phys['result_variables'])}",
            "",
        ]
        if phys.get('notes'):
            lines += [
                "==== Notes",
                "",
                phys['notes'],
                "",
            ]
        lines.append("---")
        lines.append("")

    return "\n".join(lines)


def update_comsol_users_adoc(cap: dict[str, Any]) -> str:
    """Update comsol-users.adoc with links to capabilities page."""
    # Read existing file
    path = DOCS_DIR / "comsol-users.adoc"
    with open(path, encoding="utf-8") as f:
        content = f.read()

    # Add a reference to the capabilities page at the end
    if "xref:capabilities.adoc" not in content:
        content += "\n\n== Physics capability reference\n\n"
        content += "The full versioned capability ledger is on xref:capabilities.adoc[Physics capabilities].\n"
        content += "Each interface lists its formulations, studies, material laws, mesh support, couplings, backends, and test evidence.\n"

    return content


def update_known_limitations_adoc(cap: dict[str, Any]) -> str:
    """Update known-limitations.adoc with auto-generated limitations from capabilities."""
    path = DOCS_DIR / "known-limitations.adoc"
    with open(path, encoding="utf-8") as f:
        content = f.read()

    # Extract the "Not available yet" and "Partly supported" sections
    # and add a note that limitations are also listed per-physics in capabilities.adoc
    if "xref:capabilities.adoc" not in content:
        content += "\n\n== Per-physics limitations\n\n"
        content += "See xref:capabilities.adoc[Physics capabilities] for limitations specific to each physics interface and backend.\n"

    return content


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="Write output files (default: dry run to stdout)")
    args = ap.parse_args()

    cap = load_capabilities()

    if args.write:
        # Write capabilities.adoc
        capabilities_adoc = generate_capabilities_adoc(cap)
        out_path = DOCS_DIR / "capabilities.adoc"
        out_path.write_text(capabilities_adoc, encoding="utf-8")
        print(f"Wrote {out_path}")

        # Update comsol-users.adoc
        updated = update_comsol_users_adoc(cap)
        (DOCS_DIR / "comsol-users.adoc").write_text(updated, encoding="utf-8")
        print(f"Updated {DOCS_DIR / 'comsol-users.adoc'}")

        # Update known-limitations.adoc
        updated = update_known_limitations_adoc(cap)
        (DOCS_DIR / "known-limitations.adoc").write_text(updated, encoding="utf-8")
        print(f"Updated {DOCS_DIR / 'known-limitations.adoc'}")

        print("Done.")
    else:
        print("=== capabilities.adoc ===")
        print(generate_capabilities_adoc(cap))
        print("\n=== comsol-users.adoc (updated) ===")
        print(update_comsol_users_adoc(cap))
        print("\n=== known-limitations.adoc (updated) ===")
        print(update_known_limitations_adoc(cap))


if __name__ == "__main__":
    main()